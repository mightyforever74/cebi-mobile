let totalAdded = 0;

for (const [lang, additions] of Object.entries(TRANSLATIONS)) {
  const filePath = path.join(LOCALES_DIR, `${lang}.json`);
  if (!fs.existsSync(filePath)) {
    console.warn(`⚠ ${lang}.json bulunamadı, atlanıyor`);
    continue;
  }

  let raw = fs.readFileSync(filePath, "utf8");
  // BOM strip
  if (raw.charCodeAt(0) === 0xfeff) raw = raw.slice(1);

  const json = JSON.parse(raw);
  let langAdded = 0;

  if (!json.reports) json.reports = {};

  for (const [key, value] of Object.entries(additions.reports)) {
    if (json.reports[key] === undefined) {
      json.reports[key] = value;
      langAdded++;
      totalAdded++;
    }
  }

  if (langAdded > 0) {
    fs.writeFileSync(filePath, JSON.stringify(json, null, 2) + "\n", "utf8");
    console.log(`✓ ${lang}.json: ${langAdded} anahtar eklendi`);
  } else {
    console.log(`= ${lang}.json: değişiklik yok`);
  }
}

console.log(`\nToplam ${totalAdded} ekleme yapıldı.`);
